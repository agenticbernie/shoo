/**
 * Machine-readable route registry for the `/v1` surface described in docs/37.
 *
 * The registry is the single source used by the API composition root, the contract
 * snapshot test and generated client fixtures. Adding a route is additive; removing or
 * renaming one is a breaking change requiring a new major path (docs/64 "API versioning").
 */

export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE';

export interface RouteDefinition {
  readonly method: HttpMethod;
  readonly path: string;
  /** Whether the endpoint mutates state and therefore requires `Idempotency-Key`. */
  readonly mutating: boolean;
  /** Requires recent reauthentication or wallet confirmation (docs/33 "Step-up actions"). */
  readonly stepUp: boolean;
  /** Requires a preview token bound to actor, target version and action (docs/37). */
  readonly previewToken: boolean;
  readonly params?: z.ZodTypeAny;
  readonly query?: z.ZodTypeAny;
  readonly body?: z.ZodTypeAny;
  readonly response: z.ZodTypeAny;
  /** Successful status codes this route may return. */
  readonly statuses: readonly number[];
  readonly summary: string;
}

