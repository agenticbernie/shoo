export type RouteName = keyof typeof HTTP_ROUTES;

/** Stable, sorted route signatures used by the contract snapshot fitness test (FIT-002). */
export function routeSignatures(): readonly string[] {
  return Object.values(HTTP_ROUTES)
    .map((route) => `${route.method} ${route.path}`)
    .sort();
}
